-- 전국 소매가 7일 예측. 같은 실행의 예측과 가이드를 함께 공개한다.
CREATE TABLE price_model_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES item(id),
    base_date DATE NOT NULL,
    data_date DATE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('RUNNING','SUCCESS','FAILED','INSUFFICIENT_DATA')),
    model_name VARCHAR(30),
    model_version VARCHAR(50),
    quality VARCHAR(20) CHECK (quality IN ('VALIDATED','BASELINE','UNVALIDATED')),
    metrics JSONB,
    error_code VARCHAR(40),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    finished_at TIMESTAMP,
    CHECK (data_date IS NULL OR data_date <= base_date)
);
CREATE INDEX idx_price_model_run_item ON price_model_run(item_id,base_date DESC,id DESC);
ALTER TABLE price_forecast ADD COLUMN model_run_id BIGINT REFERENCES price_model_run(id);
ALTER TABLE price_insight ADD COLUMN model_run_id BIGINT REFERENCES price_model_run(id);
-- 예측구간 보정·검증 표본이 부족하면 상하한은 NULL.
ALTER TABLE price_forecast ALTER COLUMN lower_price DROP NOT NULL,
    ALTER COLUMN upper_price DROP NOT NULL;
ALTER TABLE price_forecast ADD CONSTRAINT ck_forecast_prices CHECK (
    predicted_price > 0 AND
    ((lower_price IS NULL AND upper_price IS NULL) OR
     (lower_price IS NOT NULL AND upper_price IS NOT NULL AND lower_price >= 0
      AND lower_price <= predicted_price AND predicted_price <= upper_price)));
ALTER TABLE price_forecast ADD CONSTRAINT ck_forecast_horizon
    CHECK (target_date BETWEEN base_date + 1 AND base_date + 7);
ALTER TABLE price_daily ADD CONSTRAINT ck_price_daily_positive CHECK (price > 0);
ALTER TABLE price_insight ALTER COLUMN mape TYPE NUMERIC(12,4);
ALTER TABLE price_insight ADD CONSTRAINT ck_insight_days CHECK (buy_after_days BETWEEN 1 AND 7);
ALTER TABLE price_insight ADD CONSTRAINT ck_insight_saving CHECK (expected_saving >= 0);
CREATE INDEX idx_price_forecast_run ON price_forecast(model_run_id,target_date);
COMMENT ON TABLE price_model_run IS '예측 실행 이력·모델 선택·백테스트 및 예측구간 평가';
