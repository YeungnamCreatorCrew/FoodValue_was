-- =====================================================================
-- FoodValue V2 : 가격 예측 입력 테이블 6개 + 식자재 영양소 1개
-- 기존 테이블은 바꾸지 않고 옆에 붙인다. 모두 배치가 적재하고 앱 API 는 없음
-- MySQL 명세의 TINYINT 는 PostgreSQL 에 없어서 SMALLINT 로 옮김
-- =====================================================================


-- ---------------------------------------------------------------------
-- 전국 날씨 (하루 1행, 관측/예보 구분)
-- ---------------------------------------------------------------------
CREATE TABLE weather_daily (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weather_date             DATE         NOT NULL,
    data_type                VARCHAR(10)  NOT NULL,   -- ACTUAL 관측, FORECAST 예보 (예보는 최신으로 덮어씀)
    avg_temp                 NUMERIC(4,1),            -- ℃
    max_temp                 NUMERIC(4,1),
    min_temp                 NUMERIC(4,1),
    precipitation            NUMERIC(6,1),            -- mm
    avg_humidity             NUMERIC(4,1),            -- %
    sunshine_hours           NUMERIC(4,1),            -- 예보 행은 NULL
    heat_station_ratio       NUMERIC(5,2),            -- 최고 33℃ 이상 관측소 비율(%)
    heavy_rain_station_ratio NUMERIC(5,2),            -- 일강수 80mm 이상 관측소 비율(%)
    cold_station_ratio       NUMERIC(5,2),            -- 최저 -12℃ 이하 관측소 비율(%)
    station_count            INT,
    created_at               TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_weather_daily UNIQUE (weather_date, data_type),
    CONSTRAINT ck_weather_daily_data_type CHECK (data_type IN ('ACTUAL', 'FORECAST'))
);
COMMENT ON TABLE weather_daily IS '전국 날씨';


-- ---------------------------------------------------------------------
-- 식자재 생산량 (반입량 일 / 생산 전망 월 / 생산량 연)
-- ---------------------------------------------------------------------
CREATE TABLE item_production (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id      BIGINT        NOT NULL REFERENCES item (id),
    measure_type VARCHAR(20)   NOT NULL,
    period_type  VARCHAR(10)   NOT NULL,
    period_start DATE          NOT NULL,
    period_end   DATE          NOT NULL,   -- DAY 면 period_start 와 같음
    volume       NUMERIC(14,1) NOT NULL,
    volume_unit  VARCHAR(10)   NOT NULL,
    is_estimate  BOOLEAN       NOT NULL,   -- KREI 전망치면 true
    source       VARCHAR(20)   NOT NULL,
    created_at   TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT uk_item_production
        UNIQUE (item_id, measure_type, period_type, period_start, is_estimate),
    CONSTRAINT ck_item_production_measure_type CHECK (measure_type IN ('PRODUCTION', 'ARRIVAL')),
    CONSTRAINT ck_item_production_period_type  CHECK (period_type IN ('DAY', 'MONTH', 'YEAR')),
    CONSTRAINT ck_item_production_volume_unit  CHECK (volume_unit IN ('TON', 'KG')),
    CONSTRAINT ck_item_production_source       CHECK (source IN ('GARAK', 'KOSIS', 'KREI')),
    CONSTRAINT ck_item_production_period       CHECK (period_end >= period_start)
);
COMMENT ON TABLE item_production IS '식자재 생산량';


-- ---------------------------------------------------------------------
-- 캘린더 (날짜 차원, 몇 년치 미리 채움)
-- ---------------------------------------------------------------------
CREATE TABLE calendar_day (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cal_date         DATE        NOT NULL,
    day_of_week      SMALLINT    NOT NULL,   -- 1 월 ~ 7 일
    is_holiday       BOOLEAN     NOT NULL,   -- 대체·임시공휴일 포함, 주말 제외
    holiday_name     VARCHAR(30),
    lunar_month      SMALLINT    NOT NULL,
    lunar_day        SMALLINT    NOT NULL,
    is_lunar_leap    BOOLEAN     NOT NULL,
    is_market_closed BOOLEAN     NOT NULL,   -- 도매시장 휴장일 (이날 시세 결측은 정상)
    created_at       TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_calendar_day_cal_date UNIQUE (cal_date),
    CONSTRAINT ck_calendar_day_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_calendar_day_lunar       CHECK (lunar_month BETWEEN 1 AND 12 AND lunar_day BETWEEN 1 AND 30)
);
COMMENT ON TABLE calendar_day IS '캘린더';


-- ---------------------------------------------------------------------
-- 특수 이벤트 (연도별 실제 기간 + 가격 영향 기간)
-- ---------------------------------------------------------------------
CREATE TABLE calendar_event (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_code        VARCHAR(30) NOT NULL,   -- SEOLLAL, CHUSEOK, KIMJANG, BOKNAL ... (서버 상수)
    name              VARCHAR(50) NOT NULL,   -- 예: 2026 추석
    start_date        DATE        NOT NULL,
    end_date          DATE        NOT NULL,
    effect_start_date DATE        NOT NULL,   -- 예: 추석 D-14
    effect_end_date   DATE        NOT NULL,   -- 예: 추석 D+3
    created_at        TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_calendar_event UNIQUE (event_code, start_date),
    CONSTRAINT ck_calendar_event_period CHECK (end_date >= start_date AND effect_end_date >= effect_start_date)
);
COMMENT ON TABLE calendar_event IS '특수 이벤트';


-- ---------------------------------------------------------------------
-- 이벤트 품목 가중치 (event_code 에 연결, 품목 또는 카테고리 중 하나)
-- ---------------------------------------------------------------------
CREATE TABLE event_item_weight (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_code    VARCHAR(30)  NOT NULL,   -- calendar_event.event_code (연도별 행이 아니라 코드에 연결해서 FK 없음)
    item_id       BIGINT       REFERENCES item (id),
    category      VARCHAR(20),
    weight        NUMERIC(4,2) NOT NULL,   -- 양수 상승 압력, 음수 하락 압력
    weight_source VARCHAR(10)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_event_item_weight_item     UNIQUE (event_code, item_id),
    CONSTRAINT uk_event_item_weight_category UNIQUE (event_code, category),
    -- item_id 와 category 는 둘 중 정확히 하나만 채운다
    CONSTRAINT ck_event_item_weight_target   CHECK ((item_id IS NULL) <> (category IS NULL)),
    CONSTRAINT ck_event_item_weight_category
        CHECK (category IS NULL OR category IN ('VEGETABLE', 'GRAIN', 'FRUIT', 'MEAT', 'SEAFOOD', 'ETC')),
    CONSTRAINT ck_event_item_weight_weight   CHECK (weight BETWEEN -1.00 AND 1.00),
    CONSTRAINT ck_event_item_weight_source   CHECK (weight_source IN ('MANUAL', 'LEARNED'))
);
CREATE INDEX idx_event_item_weight_item_id ON event_item_weight (item_id);
COMMENT ON TABLE event_item_weight IS '이벤트 품목 가중치';


-- ---------------------------------------------------------------------
-- 같은 날 과거 가격 변동률 (연도별 원값, 미래 정보 누수 방지)
-- ---------------------------------------------------------------------
CREATE TABLE price_change_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id      BIGINT       NOT NULL REFERENCES item (id),
    region       VARCHAR(20)  NOT NULL DEFAULT 'NATIONAL',
    price_year   SMALLINT     NOT NULL,
    month_day    CHAR(5)      NOT NULL,   -- 예: 10-05, 2월 29일은 02-28 로 합침
    horizon_days SMALLINT     NOT NULL,   -- 1 ~ 7
    base_price   INT          NOT NULL,   -- 휴장일이면 직전 거래일 가격
    change_rate  NUMERIC(6,2) NOT NULL,   -- %
    created_at   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_price_change_history
        UNIQUE (item_id, region, price_year, month_day, horizon_days),
    CONSTRAINT ck_price_change_history_horizon   CHECK (horizon_days BETWEEN 1 AND 7),
    CONSTRAINT ck_price_change_history_month_day CHECK (month_day ~ '^(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])$')
);
COMMENT ON TABLE price_change_history IS '같은 날 과거 가격 변동률';


-- ---------------------------------------------------------------------
-- 식자재 영양소 (item 과 1:1, 가식부 100g 기준, NULL 은 측정값 없음)
-- ---------------------------------------------------------------------
CREATE TABLE item_nutrition (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id         BIGINT       NOT NULL REFERENCES item (id) ON DELETE CASCADE,
    food_code       VARCHAR(30),
    edible_ratio    NUMERIC(5,2),   -- %
    energy_kcal     NUMERIC(7,2),
    water_g         NUMERIC(7,2),
    protein_g       NUMERIC(7,2),
    fat_g           NUMERIC(7,2),
    saturated_fat_g NUMERIC(7,2),
    carbohydrate_g  NUMERIC(7,2),
    sugars_g        NUMERIC(7,2),
    dietary_fiber_g NUMERIC(7,2),
    sodium_mg       NUMERIC(8,2),
    potassium_mg    NUMERIC(8,2),
    calcium_mg      NUMERIC(8,2),
    iron_mg         NUMERIC(7,2),
    vitamin_a_ug    NUMERIC(8,2),   -- μg RAE
    vitamin_c_mg    NUMERIC(7,2),
    cholesterol_mg  NUMERIC(8,2),
    source          VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_item_nutrition_item_id UNIQUE (item_id),
    CONSTRAINT ck_item_nutrition_source  CHECK (source IN ('MFDS', 'RDA')),
    CONSTRAINT ck_item_nutrition_edible  CHECK (edible_ratio IS NULL OR edible_ratio BETWEEN 0 AND 100)
);
COMMENT ON TABLE item_nutrition IS '식자재 영양소';
