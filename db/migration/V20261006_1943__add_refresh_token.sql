-- 리프레시 토큰: 원문이 아니라 SHA-256 해시만 저장한다.
-- family_id: 로그인 한 번에 하나. 재발급(회전)해도 유지되고, 폐기된 토큰이 재사용되면 같은 family 전체를 폐기한다.
CREATE TABLE refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    family_id  UUID         NOT NULL,
    token_hash CHAR(64)     NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_token_user   ON refresh_token (user_id);
CREATE INDEX idx_refresh_token_family ON refresh_token (family_id);

COMMENT ON TABLE  refresh_token            IS '리프레시 토큰 (해시 저장)';
COMMENT ON COLUMN refresh_token.family_id  IS '로그인 단위 토큰 계열. 재사용 탐지 시 계열 전체 폐기';
COMMENT ON COLUMN refresh_token.token_hash IS '토큰 원문의 SHA-256 hex';
COMMENT ON COLUMN refresh_token.revoked_at IS '폐기 시각 (회전·로그아웃). NULL 이면 유효';
