-- 한국은행 ECOS 일별 환율. 원본은 external_observation에 보존하고 여기에는 통화별 정제값만 둔다.
CREATE TABLE exchange_rate_daily (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_date DATE NOT NULL,
    currency_code VARCHAR(10) NOT NULL,   -- USD 등
    rate NUMERIC(12,4) NOT NULL CHECK (rate > 0),   -- 원화 환산 매매기준율
    unit_label VARCHAR(30) NOT NULL,      -- 예: 원/미국달러
    source VARCHAR(20) NOT NULL DEFAULT 'ECOS' CHECK (source IN ('ECOS')),
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT uk_exchange_rate_daily UNIQUE (rate_date, currency_code)
);
COMMENT ON TABLE exchange_rate_daily IS '일별 환율(ECOS 731Y001 매매기준율). 예측 모델 입력에는 사용하지 않음';
