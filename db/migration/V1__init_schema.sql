-- =====================================================================
-- FoodValue V1 : 1단계 핵심 테이블 9개 + 커뮤니티 테이블 3개
-- PostgreSQL 15+ / Supabase 호환
--
-- 규칙: 팀에 공유된 뒤에는 이 파일을 수정하지 않는다.
--       컬럼 추가·변경은 V2__xxx.sql, V3__xxx.sql 처럼 새 파일로 한다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 사용자
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nickname      VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email    UNIQUE (email),
    CONSTRAINT uk_users_nickname UNIQUE (nickname)
);
COMMENT ON TABLE users IS '사용자';


-- ---------------------------------------------------------------------
-- 품목 마스터 (재료·시세·레시피가 공유)
-- ---------------------------------------------------------------------
CREATE TABLE item (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(50) NOT NULL,
    category           VARCHAR(20) NOT NULL,
    default_unit       VARCHAR(10) NOT NULL,
    default_storage    VARCHAR(10) NOT NULL,
    shelf_days_fridge  INT,
    shelf_days_freezer INT,
    shelf_days_room    INT,
    kamis_code         VARCHAR(20),          -- NULL 이면 시세 미제공. 형식은 팀 합의 (예: 품목-품종-등급)
    price_unit_label   VARCHAR(30),          -- 예: 1단 · 800g
    created_at         TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_item_name       UNIQUE (name),
    CONSTRAINT uk_item_kamis_code UNIQUE (kamis_code),   -- NULL 은 여러 개 허용됨
    CONSTRAINT ck_item_category
        CHECK (category IN ('VEGETABLE', 'GRAIN', 'FRUIT', 'MEAT', 'SEAFOOD', 'ETC')),
    CONSTRAINT ck_item_default_storage
        CHECK (default_storage IN ('FRIDGE', 'FREEZER', 'ROOM'))
);
COMMENT ON TABLE item IS '품목 마스터';


-- ---------------------------------------------------------------------
-- 품목 별칭 (파, 다진 파, 흙대파 → 대파)
-- ---------------------------------------------------------------------
CREATE TABLE item_alias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id    BIGINT      NOT NULL REFERENCES item (id) ON DELETE CASCADE,
    alias      VARCHAR(50) NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_item_alias_alias UNIQUE (alias)
);
CREATE INDEX idx_item_alias_item_id ON item_alias (item_id);
COMMENT ON TABLE item_alias IS '품목 별칭';


-- ---------------------------------------------------------------------
-- 냉장고 재료
-- ---------------------------------------------------------------------
CREATE TABLE fridge_ingredient (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT        NOT NULL REFERENCES users (id),
    item_id          BIGINT                 REFERENCES item (id) ON DELETE SET NULL, -- 자동완성에 없으면 NULL
    display_name     VARCHAR(50)   NOT NULL,
    quantity         NUMERIC(10,1) NOT NULL,
    initial_quantity NUMERIC(10,1) NOT NULL,
    unit             VARCHAR(10)   NOT NULL,  -- g, kg, ml, 개, 단, 모, 팩, 봉, 송이 (서버 상수로 검증)
    storage          VARCHAR(10)   NOT NULL,
    purchased_at     DATE          NOT NULL,
    expires_at       DATE          NOT NULL,
    created_at       TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_fridge_ingredient_storage  CHECK (storage IN ('FRIDGE', 'FREEZER', 'ROOM')),
    CONSTRAINT ck_fridge_ingredient_quantity CHECK (quantity >= 0 AND initial_quantity > 0)
);
CREATE INDEX idx_fridge_ingredient_user_id ON fridge_ingredient (user_id);
CREATE INDEX idx_fridge_ingredient_item_id ON fridge_ingredient (item_id);
COMMENT ON TABLE fridge_ingredient IS '냉장고 재료';


-- ---------------------------------------------------------------------
-- 재료 사용 기록 (재료 삭제 시 함께 삭제)
-- ---------------------------------------------------------------------
CREATE TABLE ingredient_usage (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fridge_ingredient_id BIGINT        NOT NULL REFERENCES fridge_ingredient (id) ON DELETE CASCADE,
    used_amount          NUMERIC(10,1) NOT NULL,
    memo                 VARCHAR(100),
    used_at              DATE          NOT NULL,
    created_at           TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_ingredient_usage_amount CHECK (used_amount > 0)
);
CREATE INDEX idx_ingredient_usage_fridge_ingredient_id ON ingredient_usage (fridge_ingredient_id);
COMMENT ON TABLE ingredient_usage IS '재료 사용 기록';


-- ---------------------------------------------------------------------
-- 일별 시세 (배치 적재, API 는 조회만)
-- ---------------------------------------------------------------------
CREATE TABLE price_daily (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id    BIGINT      NOT NULL REFERENCES item (id),
    region     VARCHAR(20) NOT NULL,   -- NATIONAL, SEOUL, DAEGU ... (KAMIS 지역코드 대응표는 팀 합의)
    price_date DATE        NOT NULL,
    price      INT         NOT NULL,   -- 원, item.price_unit_label 기준
    created_at TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_price_daily UNIQUE (item_id, region, price_date)
);
COMMENT ON TABLE price_daily IS '일별 시세';


-- ---------------------------------------------------------------------
-- 시세 예측
-- ---------------------------------------------------------------------
CREATE TABLE price_forecast (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id         BIGINT    NOT NULL REFERENCES item (id),
    base_date       DATE      NOT NULL,   -- 예측 실행일
    target_date     DATE      NOT NULL,   -- 기준일 + 1~7일
    predicted_price INT       NOT NULL,
    lower_price     INT       NOT NULL,   -- 95% 신뢰구간 하단
    upper_price     INT       NOT NULL,   -- 95% 신뢰구간 상단
    created_at      TIMESTAMP NOT NULL DEFAULT now(),
    -- 명세에 없던 제약: 배치를 다시 돌려도 중복이 쌓이지 않도록 추가
    CONSTRAINT uk_price_forecast UNIQUE (item_id, base_date, target_date)
);
COMMENT ON TABLE price_forecast IS '시세 예측';


-- ---------------------------------------------------------------------
-- 구매 가이드
-- ---------------------------------------------------------------------
CREATE TABLE price_insight (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id         BIGINT      NOT NULL REFERENCES item (id),
    base_date       DATE        NOT NULL,
    recommendation  VARCHAR(20) NOT NULL,
    buy_after_days  INT,                  -- BUY_LATER 일 때 N일
    expected_saving INT,                  -- 원
    mape            NUMERIC(5,2),         -- %
    factors         JSONB,                -- [{name, direction, contribution, description}, ...]
    created_at      TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT uk_price_insight UNIQUE (item_id, base_date),
    CONSTRAINT ck_price_insight_recommendation
        CHECK (recommendation IN ('BUY_NOW', 'BUY_LATER', 'HOLD', 'STABLE'))
);
COMMENT ON TABLE price_insight IS '구매 가이드';


-- ---------------------------------------------------------------------
-- 저장한 레시피 (LLM 응답 JSON 그대로)
-- ---------------------------------------------------------------------
CREATE TABLE saved_recipe (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    title      VARCHAR(100) NOT NULL,
    content    JSONB        NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_saved_recipe_user_id ON saved_recipe (user_id);
COMMENT ON TABLE saved_recipe IS '저장한 레시피';


-- =====================================================================
-- 커뮤니티
-- =====================================================================

CREATE TABLE post (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    category   VARCHAR(20)  NOT NULL,
    title      VARCHAR(100) NOT NULL,
    content    TEXT         NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT ck_post_category CHECK (category IN ('RECIPE_SHARE', 'GROUP_BUY', 'SHOWOFF'))
);
CREATE INDEX idx_post_created_at          ON post (created_at DESC);
CREATE INDEX idx_post_category_created_at ON post (category, created_at DESC);
COMMENT ON TABLE post IS '게시글';


CREATE TABLE post_image (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT       NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    url        VARCHAR(500) NOT NULL,
    sort_order INT          NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX idx_post_image_post_id ON post_image (post_id, sort_order);
COMMENT ON TABLE post_image IS '게시글 이미지';


CREATE TABLE comment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT    NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    user_id    BIGINT    NOT NULL REFERENCES users (id),
    content    TEXT      NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_comment_post_id ON comment (post_id, created_at);
COMMENT ON TABLE comment IS '댓글';
