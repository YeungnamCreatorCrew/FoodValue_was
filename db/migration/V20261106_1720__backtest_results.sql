-- 가격 예측 중심 스키마 3: 백테스트 결과를 DB에 남긴다(python -m app.price_backtest --save).
-- 모델·설정을 바꿀 때마다 같은 기준으로 비교할 수 있게 실행 조건·요약·기준일별 선택·시점별 비교를 저장한다.

CREATE TABLE backtest_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id     BIGINT      NOT NULL REFERENCES price_series (id),   -- 예측 대상 계열(소매 또는 도매)
    model_version VARCHAR(50) NOT NULL,
    git_commit    VARCHAR(40),
    start_date    DATE        NOT NULL,   -- 첫 기준일
    end_date      DATE        NOT NULL,   -- 마지막 기준일
    every_days    SMALLINT    NOT NULL,   -- 기준일 간격
    summary       JSONB       NOT NULL,   -- 전체·시점별·모델별 MAPE·naive 대비 개선율 등
    note          VARCHAR(200),
    created_at    TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT ck_backtest_run_period CHECK (end_date >= start_date AND every_days >= 1)
);
CREATE INDEX idx_backtest_run_series ON backtest_run (series_id, created_at DESC);
COMMENT ON TABLE backtest_run IS '백테스트 실행. 비교 기준은 직전 가격 유지(naive)';

CREATE TABLE backtest_origin (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    backtest_run_id BIGINT      NOT NULL REFERENCES backtest_run (id) ON DELETE CASCADE,
    base_date       DATE        NOT NULL,
    status          VARCHAR(20) NOT NULL,
    model_name      VARCHAR(30),
    quality         VARCHAR(20),
    detail          JSONB,      -- 묶음 가중치, 선택 구간 후보, 내부 평가 MAPE 등
    CONSTRAINT uk_backtest_origin UNIQUE (backtest_run_id, base_date),
    CONSTRAINT ck_backtest_origin_status CHECK (status IN ('SUCCESS', 'INSUFFICIENT_DATA', 'FAILED'))
);
COMMENT ON TABLE backtest_origin IS '백테스트 기준일별 실행 결과(선택 모델·품질)';

CREATE TABLE backtest_point (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    backtest_run_id BIGINT      NOT NULL REFERENCES backtest_run (id) ON DELETE CASCADE,
    base_date       DATE        NOT NULL,
    target_date     DATE        NOT NULL,
    horizon         SMALLINT    NOT NULL,
    model_name      VARCHAR(30) NOT NULL,
    quality         VARCHAR(20) NOT NULL,
    current_price   INT         NOT NULL,   -- 기준일의 최신 관측가 = naive 예측
    predicted_price INT         NOT NULL,
    lower_price     INT,
    upper_price     INT,
    actual_price    INT         NOT NULL,
    CONSTRAINT uk_backtest_point UNIQUE (backtest_run_id, base_date, target_date),
    CONSTRAINT ck_backtest_point_horizon CHECK (horizon BETWEEN 1 AND 7 AND target_date = base_date + horizon)
);
COMMENT ON TABLE backtest_point IS '백테스트 시점별 비교. 실제 가격이 있는 목표일만 저장한다';
