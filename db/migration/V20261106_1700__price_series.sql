-- 가격 예측 중심 스키마 1: 가격 계열(price_series)
--
-- 품목 하나에 KAMIS 계열이 시장(소매·도매)별로 하나씩 있다. 두 계열 모두 예측 대상이고, 서로의 가격을 예측 변수로 쓴다.
-- 이전에는 item.price_code 문자열 하나를 소매·도매가 같이 썼고, 도매가는 정형 테이블 없이 원본(external_observation)에만 있었다.
-- 이제 price_daily·price_change_history는 품목이 아니라 계열을 가리키고, 도매가도 price_daily에 들어간다.
-- 지역은 전국(KAMIS '평균')만 쓰므로 region 컬럼을 없앤다.

CREATE TABLE price_series (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id       BIGINT        NOT NULL REFERENCES item (id),
    source        VARCHAR(10)   NOT NULL DEFAULT 'KAMIS',
    market        VARCHAR(10)   NOT NULL,
    item_code     VARCHAR(3)    NOT NULL,   -- KAMIS 품목코드 (예: 246 대파). 부류코드는 첫 자리 + '00'
    kind_code     VARCHAR(2)    NOT NULL,   -- 품종코드 (예: 00)
    rank_code     VARCHAR(2)    NOT NULL,   -- 등급코드 (예: 04 상품)
    unit_quantity NUMERIC(10,3) NOT NULL,   -- 가격 단위 수량 (예: 1)
    unit          VARCHAR(10)   NOT NULL,   -- 가격 단위 (예: kg, 개, 포기). KAMIS 표기를 그대로 쓴다
    created_at    TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_price_series_source   CHECK (source IN ('KAMIS')),
    CONSTRAINT ck_price_series_market   CHECK (market IN ('RETAIL', 'WHOLESALE')),
    CONSTRAINT ck_price_series_codes    CHECK (item_code ~ '^[0-9]{3}$' AND kind_code ~ '^[0-9]{2}$' AND rank_code ~ '^[0-9]{2}$'),
    CONSTRAINT ck_price_series_quantity CHECK (unit_quantity > 0),
    CONSTRAINT uk_price_series_item_market UNIQUE (item_id, market),
    CONSTRAINT uk_price_series_code        UNIQUE (source, market, item_code, kind_code, rank_code)
);
COMMENT ON TABLE price_series IS '가격 계열: 품목 × 시장(RETAIL·WHOLESALE). 계열마다 예측하며 상대 시장 가격을 예측 변수로 쓴다. KAMIS 품목·품종·등급 코드와 가격 단위';

-- 기존 KAMIS 품목(price_code가 품목-품종-등급 형식인 것)을 소매·도매 계열로 옮긴다. 단위는 price_unit_label(예: 1kg)에서 나눈다.
INSERT INTO price_series (item_id, market, item_code, kind_code, rank_code, unit_quantity, unit)
SELECT i.id, m.market, split_part(i.price_code, '-', 1), split_part(i.price_code, '-', 2), split_part(i.price_code, '-', 3),
       substring(i.price_unit_label FROM '^\s*([0-9]+(?:\.[0-9]+)?)')::NUMERIC,
       trim(regexp_replace(i.price_unit_label, '^\s*[0-9]+(\.[0-9]+)?\s*', ''))
FROM item i CROSS JOIN (VALUES ('RETAIL'), ('WHOLESALE')) AS m (market)
WHERE i.price_source = 'KAMIS'
  AND i.price_code ~ '^[0-9]{3}-[0-9]{2}-[0-9]{2}$'
  AND i.price_unit_label ~ '^\s*[0-9]+(\.[0-9]+)?\s*\S';

-- price_daily: 품목·지역 → 계열. 원본 관측 행을 추적할 수 있게 observation_id를 둔다.
ALTER TABLE price_daily ADD COLUMN series_id BIGINT REFERENCES price_series (id);
ALTER TABLE price_daily ADD COLUMN observation_id BIGINT REFERENCES external_observation (id);
UPDATE price_daily d SET series_id = s.id
FROM price_series s WHERE s.item_id = d.item_id AND s.market = 'RETAIL' AND d.region = 'NATIONAL';
DELETE FROM price_daily WHERE series_id IS NULL;   -- 계열로 옮길 수 없는 행(형식이 다른 테스트 품목 등)
ALTER TABLE price_daily ALTER COLUMN series_id SET NOT NULL;
ALTER TABLE price_daily DROP CONSTRAINT uk_price_daily;
ALTER TABLE price_daily DROP COLUMN item_id, DROP COLUMN region;
ALTER TABLE price_daily ADD CONSTRAINT uk_price_daily UNIQUE (series_id, price_date);
COMMENT ON TABLE price_daily IS '계열별 일별 전국 가격(원, price_series 단위 기준). external_observation에서 정제해 적재한다';
COMMENT ON COLUMN price_daily.observation_id IS '이 값을 만든 external_observation 행(원천 최신 버전)';

-- price_change_history: 품목·지역 → 계열. 기존 행은 소매 계열로 옮기고 도매 계열은 정제 단계에서 새로 만든다
ALTER TABLE price_change_history ADD COLUMN series_id BIGINT REFERENCES price_series (id);
UPDATE price_change_history h SET series_id = s.id
FROM price_series s WHERE s.item_id = h.item_id AND s.market = 'RETAIL' AND h.region = 'NATIONAL';
DELETE FROM price_change_history WHERE series_id IS NULL;
ALTER TABLE price_change_history ALTER COLUMN series_id SET NOT NULL;
ALTER TABLE price_change_history DROP CONSTRAINT uk_price_change_history;
ALTER TABLE price_change_history DROP COLUMN item_id, DROP COLUMN region;
ALTER TABLE price_change_history ADD CONSTRAINT uk_price_change_history
    UNIQUE (series_id, price_year, month_day, horizon_days);

-- item.price_code는 price_series로 옮겼다. price_source·price_unit_label은 냉장고 화면 표시용으로만 남는다.
ALTER TABLE item DROP CONSTRAINT ck_item_price_pair, DROP CONSTRAINT uk_item_price_code;
ALTER TABLE item DROP COLUMN price_code;
COMMENT ON COLUMN item.price_source IS '냉장고 화면의 시세 제공 표시용. 가격 예측은 price_series를 기준으로 한다';
COMMENT ON COLUMN item.price_unit_label IS '냉장고 화면 표시용 단위. 가격 예측 단위는 price_series.unit_quantity·unit';
