-- KREI 관측월보(·속보)에서 추출한 수치. 원본 호는 external_observation(KREI, MONTHLY_REPORT)에 있고,
-- 여기에는 "값 1개 = 1행"으로 정제값만 둔다.
--
-- 설계 기준
-- - 예측 재현성: published_at은 원본 호의 발표 시점을 복사한다(NOT NULL). 발표 시점을 모르는 호(UNKNOWN)의 값은 넣지 않는다.
--   모델은 기준일 d에 published_at < d인 행만 쓴다.
-- - 원본 추적: observation_id가 값이 나온 원본 호의 "버전"을 가리킨다. KREI가 호를 고쳐 올리면 새 버전 → 새 행이 생기고
--   예전 값은 지워지지 않는다(같은 대상 기간을 여러 호가 전망해도 덮어쓰지 않음).
-- - item_production을 쓰지 않는 이유: 발표 시점·원본 id가 없고, 유니크 키 때문에 같은 달 전망을 하나만 담으며,
--   값이 절대량(NOT NULL)뿐이라 "전년 대비 9%"·"증가 전망" 같은 월보 수치를 담을 수 없다.
-- - 품목은 KREI 표기(item_name: 대파·양파·마늘·배추·무 …)와 작형(crop_type: 가을·월동 …)으로 둔다.
--   우리 item은 배추·무가 작형별 품목이고 깐마늘은 KREI에서 마늘이라 1:1이 아니다. 계열 연결은 로더에서 한다.

CREATE TABLE krei_report_value (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id    BIGINT        NOT NULL REFERENCES external_observation (id),
    published_at      TIMESTAMPTZ   NOT NULL,   -- 원본 호 발표 시점 복사
    item_name         VARCHAR(30)   NOT NULL,   -- KREI 품목명 (대파, 마늘, 배추 …)
    crop_type         VARCHAR(30),              -- 작형·구분 (가을, 월동, 고랭지, 시설, 노지 …). 품목 전체면 NULL
    metric            VARCHAR(30)   NOT NULL,
    kind              VARCHAR(10)   NOT NULL,   -- OUTLOOK 전망, ACTUAL 지난 기간 실적
    target_start      DATE          NOT NULL,   -- 값이 가리키는 기간 (월·순 단위)
    target_end        DATE          NOT NULL,
    basis             VARCHAR(20)   NOT NULL,   -- LEVEL 절대값, PREV_YEAR 전년 대비, NORMAL 평년 대비, PREV_MONTH 전월 대비
    value             NUMERIC(14,3),            -- 점 값. "800원 내외"=800, 범위면 중간값. 숫자가 없으면 NULL
    value_low         NUMERIC(14,3),            -- 범위 하한 ("1,000~1,200원" → 1000)
    value_high        NUMERIC(14,3),            -- 범위 상한
    unit              VARCHAR(20),              -- %, 원/kg, 원/10kg, 톤, ha, kg/10a …
    direction         VARCHAR(10),              -- UP / DOWN / FLAT. 숫자 없이 "증가 전망"만 있을 때도 채운다
    evidence          TEXT          NOT NULL,   -- 값을 뽑은 원문 문장 (사람 대조용)
    extractor         VARCHAR(40)   NOT NULL,   -- regex / claude-… / gemini-…
    extractor_version VARCHAR(40)   NOT NULL,   -- 규칙·프롬프트 버전
    created_at        TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT ck_krei_report_value_metric CHECK (metric IN (
        'PLANTED_AREA',     -- 재배·정식·파종 면적
        'SHIPMENT_AREA',    -- 출하 면적
        'YIELD',            -- 단수
        'PRODUCTION',       -- 생산량
        'SHIPMENT',         -- 출하량
        'ARRIVAL',          -- 도매시장 반입량
        'STOCK',            -- 저장(재고)량
        'IMPORT',           -- 수입량
        'WHOLESALE_PRICE',  -- 도매가격
        'RETAIL_PRICE')),   -- 소매가격
    CONSTRAINT ck_krei_report_value_kind  CHECK (kind IN ('OUTLOOK', 'ACTUAL')),
    CONSTRAINT ck_krei_report_value_basis CHECK (basis IN ('LEVEL', 'PREV_YEAR', 'NORMAL', 'PREV_MONTH')),
    CONSTRAINT ck_krei_report_value_direction CHECK (direction IS NULL OR direction IN ('UP', 'DOWN', 'FLAT')),
    CONSTRAINT ck_krei_report_value_has_value CHECK (value IS NOT NULL OR direction IS NOT NULL),
    CONSTRAINT ck_krei_report_value_range CHECK (value_low IS NULL OR value_high IS NULL OR value_low <= value_high),
    CONSTRAINT ck_krei_report_value_unit  CHECK (value IS NULL OR unit IS NOT NULL),
    CONSTRAINT ck_krei_report_value_period CHECK (target_end >= target_start),
    -- 한 호 버전에서 같은 사실은 1행. 다시 추출하면 upsert로 값·추출기를 갱신한다.
    CONSTRAINT uk_krei_report_value UNIQUE NULLS NOT DISTINCT
        (observation_id, item_name, crop_type, metric, kind, basis, target_start, target_end)
);
CREATE INDEX idx_krei_report_value_lookup ON krei_report_value (item_name, metric, kind, published_at);

COMMENT ON TABLE krei_report_value IS
    'KREI 관측월보·속보에서 추출한 수치(값 1개=1행). published_at(원본 호 발표 시점) 이전 기준일에는 쓰지 않는다. '
    '원본 호 버전은 observation_id, 근거 문장은 evidence';
