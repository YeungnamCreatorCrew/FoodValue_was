-- 예측 원천은 지역·관측소·발표시점·수정버전을 보존한다. 기존 전국 집계에 섞지 않는다.
CREATE TABLE external_collection_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(30) NOT NULL,
    dataset VARCHAR(60) NOT NULL,
    start_date DATE,
    end_date DATE,
    status VARCHAR(20) NOT NULL CHECK (status IN
        ('RUNNING','SUCCESS','NO_DATA','PARTIAL','AUTH_ERROR','NETWORK_ERROR','FAILED','SKIPPED')),
    request_count INT NOT NULL DEFAULT 0 CHECK (request_count >= 0),
    records_received INT NOT NULL DEFAULT 0 CHECK (records_received >= 0),
    records_inserted INT NOT NULL DEFAULT 0 CHECK (records_inserted >= 0),
    error_code VARCHAR(120),
    manifest_path TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE TABLE external_observation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_run_id BIGINT NOT NULL REFERENCES external_collection_run(id),
    item_id BIGINT REFERENCES item(id),
    source VARCHAR(30) NOT NULL,
    dataset VARCHAR(60) NOT NULL,
    source_record_key VARCHAR(400) NOT NULL,
    entity_code VARCHAR(100),
    entity_name VARCHAR(150),
    observed_on DATE,
    period_start DATE,
    period_end DATE,
    issued_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    publication_status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN'
        CHECK (publication_status IN ('SOURCE_PROVIDED','UNKNOWN')),
    retrieved_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    units JSONB NOT NULL DEFAULT '{}'::JSONB,
    payload JSONB NOT NULL,
    payload_sha256 CHAR(64) NOT NULL,
    CONSTRAINT uk_external_observation UNIQUE(source,dataset,source_record_key,payload_sha256),
    CHECK (period_end IS NULL OR period_start IS NULL OR period_end >= period_start),
    CHECK (publication_status <> 'SOURCE_PROVIDED' OR published_at IS NOT NULL)
);
CREATE INDEX idx_external_observation_dataset_date ON external_observation(dataset,observed_on,entity_code);
CREATE INDEX idx_external_observation_item ON external_observation(item_id,dataset,period_start);
CREATE INDEX idx_external_observation_availability ON external_observation(published_at,issued_at);
CREATE TABLE item_weather_station (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES item(id),
    station_code VARCHAR(20) NOT NULL,
    station_name VARCHAR(100) NOT NULL,
    producing_region VARCHAR(100) NOT NULL,
    mapping_status VARCHAR(20) NOT NULL CHECK (mapping_status IN ('CANDIDATE','VERIFIED')),
    months SMALLINT[],
    share NUMERIC(6,5) CHECK (share BETWEEN 0 AND 1),
    rationale TEXT NOT NULL,
    valid_from DATE,
    valid_until DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_item_weather_station UNIQUE(item_id,station_code,producing_region),
    CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until >= valid_from)
);
COMMENT ON TABLE external_observation IS '기관별 원천 관측·예보·통계 수정 이력. 발표시점 UNKNOWN은 검증 없이 과거 모델에 사용하지 않음';
COMMENT ON TABLE item_weather_station IS '주산지 기상 연결 후보와 검증 상태. 미확인 비중은 NULL';
